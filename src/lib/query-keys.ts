export type RegisteredQueryKeyRoot = (typeof registeredQueryKeyRoots)[number];

const registeredQueryKeyRootSet = new Set<string>(registeredQueryKeyRoots);

export function isRegisteredQueryKeyRoot(value: string): value is RegisteredQueryKeyRoot {
  return registeredQueryKeyRootSet.has(value);
}

export function queryKey<const TParts extends readonly unknown[]>(
  root: RegisteredQueryKeyRoot,
  ...parts: TParts
): readonly [RegisteredQueryKeyRoot, ...TParts] {
  return [root, ...parts] as const;
}

export function getQueryKeyRoot(key: QueryKey): string | undefined {
  const [root] = key;
  return typeof root === "string" ? root : undefined;
}
